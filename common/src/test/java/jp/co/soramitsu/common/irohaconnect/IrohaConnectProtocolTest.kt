    @Test
    fun `current envelope uses canonical schema and authenticated round trip`() {
        val message = ByteArray(32) { index -> (index + 1).toByte() }
        val encoded = IrohaConnectEnvelopeWire.encode(
            2,
            IrohaConnectEnvelopePayload.SignRaw("FI_PROPOSAL_SIGN", message),
        )
        assertEquals(
            "4e52543000006947afe3e8a85446d6a3ee7bb1a37c0a",
            IrohaConnectEncoding.hex(encoded.copyOfRange(0, 22)),
        )
        val decoded = IrohaConnectEnvelopeWire.decode(encoded)
        assertEquals(2, decoded.sequence)
        val raw = decoded.payload as IrohaConnectEnvelopePayload.SignRaw
        assertEquals("FI_PROPOSAL_SIGN", raw.domainTag)
        assertArrayEquals(message, raw.message)

        val key = ByteArray(32) { (it + 9).toByte() }
        val sid = ByteArray(32) { (it + 45).toByte() }
        val ciphertext = IrohaConnectCrypto.encrypt(
            key,
            2,
            IrohaConnectWire.associatedData(sid, IrohaConnectDirection.APP_TO_WALLET, 2),
            encoded,
        )
        val authenticated = IrohaConnectEnvelopeWire.decrypt(
            key,
            sid,
            IrohaConnectDirection.APP_TO_WALLET,
            2,
            ciphertext,
        )
        assertEquals(2, authenticated.sequence)

        ciphertext[0] = (ciphertext[0].toInt() xor 1).toByte()
        assertThrows(Exception::class.java) {
            IrohaConnectEnvelopeWire.decrypt(
                key,
                sid,
                IrohaConnectDirection.APP_TO_WALLET,
                2,
                ciphertext,
            )
        }
    }

    @Test
    fun `session binds open approval permission request and signed response`() {
        val fixture = launchFixture("iroha", "https://taira.sora.org")
        val launch = IrohaConnectUri.parse(fixture.uri)
        val session = IrohaConnectWalletSession(launch, startedAtMillis = 1_000)
        val permissionDomain = URANAI_SIGNING_DOMAIN
        val permissions = IrohaConnectPermissions(
            methods = listOf("sign_raw"),
            events = emptyList(),
            resources = listOf(permissionDomain),
        )
        val open = IrohaConnectWire.encodeOpen(
            sid = launch.sid,
            appPublicKey = launch.appPublicKey,
            networkIdBytes = launch.networkIdBytes,
            appMetadata = IrohaConnectAppMetadata(
                name = "Uranai",
                url = "https://uranai.sora.org",
                iconHash = null,
            ),
            permissions = permissions,
        )
        val pairing = session.receive(open, 1_100) as IrohaConnectSessionEvent.PairingRequested
        assertEquals("Uranai", pairing.review.appName)
        assertEquals(listOf(permissionDomain), pairing.review.permissions?.resources)

        val account = IrohaKeyDerivation.derive(MNEMONIC, NexusNetworks.taira)
        try {
            val approvalEvent = session.approvePairing(account.address, 1_200) {
                IrohaConnectCrypto.signEd25519(account.privateKeySeed, it)
            }
            val approval = IrohaConnectWire.decodeFrame(approvalEvent.bytes)
                as IrohaConnectFrame.Control
            assertEquals(1, approval.sequence)
            assertEquals(IrohaConnectDirection.WALLET_TO_APP, approval.direction)
            val approvalControl = approval.control as IrohaConnectControl.Approve
            assertEquals(account.address, approvalControl.accountId)
            assertEquals(permissions, approvalControl.permissions)

            val appDirectionKeys = IrohaConnectCrypto.deriveDirectionKeys(
                sid = launch.sid,
                appPublicKey = approvalControl.walletPublicKey,
                walletPrivateKey = fixture.appKeys.privateKey,
            )
            try {
                val message = "sign this contract call".toByteArray()
                val requestEnvelope = IrohaConnectEnvelopeWire.encode(
                    2,
                    IrohaConnectEnvelopePayload.SignRaw(permissionDomain, message),
                )
                val requestCiphertext = IrohaConnectCrypto.encrypt(
                    appDirectionKeys.appToWallet,
                    2,
                    IrohaConnectWire.associatedData(
                        launch.sid,
                        IrohaConnectDirection.APP_TO_WALLET,
                        2,
                    ),
                    requestEnvelope,
                )
                val requestFrame = IrohaConnectWire.encodeCiphertext(
                    launch.sid,
                    2,
                    requestCiphertext,
                    IrohaConnectDirection.APP_TO_WALLET,
                )
                val request = session.receive(requestFrame, 1_300)
                    as IrohaConnectSessionEvent.SigningRequested
                assertEquals(IrohaConnectSigningKind.RAW, request.review.kind)
                assertEquals(permissionDomain, request.review.domainTag)
                assertEquals(String(message, Charsets.UTF_8), request.review.readableMessage)

                val concurrentEnvelope = IrohaConnectEnvelopeWire.encode(
                    3,
                    IrohaConnectEnvelopePayload.SignRaw(
                        permissionDomain,
                        "must not replace the pending request".toByteArray(),
                    ),
                )
                val concurrentCiphertext = IrohaConnectCrypto.encrypt(
                    appDirectionKeys.appToWallet,
                    3,
                    IrohaConnectWire.associatedData(
                        launch.sid,
                        IrohaConnectDirection.APP_TO_WALLET,
                        3,
                    ),
                    concurrentEnvelope,
                )
                val concurrentFrame = IrohaConnectWire.encodeCiphertext(
                    launch.sid,
                    3,
                    concurrentCiphertext,
                    IrohaConnectDirection.APP_TO_WALLET,
                )
                val concurrentResponse = session.receive(concurrentFrame, 1_350)
                    as IrohaConnectSessionEvent.SendFrame
                assertFalse(concurrentResponse.signed)
                val concurrentResponseFrame = IrohaConnectWire.decodeFrame(concurrentResponse.bytes)
                    as IrohaConnectFrame.Ciphertext
                val concurrentError = IrohaConnectEnvelopeWire.decrypt(
                    appDirectionKeys.walletToApp,
                    launch.sid,
                    IrohaConnectDirection.WALLET_TO_APP,
                    2,
                    concurrentResponseFrame.aead,
                ).payload as IrohaConnectEnvelopePayload.SignResultError
                assertEquals("REQUEST_IN_FLIGHT", concurrentError.code)

                assertThrows(IrohaConnectSessionException::class.java) {
                    session.approveRequest("wrong-token", 1_400) {
                        IrohaConnectCrypto.signEd25519(account.privateKeySeed, it)
                    }
                }
                val responseEvent = session.approveRequest(request.review.requestToken, 1_400) {
                    IrohaConnectCrypto.signEd25519(account.privateKeySeed, it)
                }
                assertTrue(responseEvent.signed)
                val response = IrohaConnectWire.decodeFrame(responseEvent.bytes)
                    as IrohaConnectFrame.Ciphertext
                val responseEnvelope = IrohaConnectEnvelopeWire.decrypt(
                    appDirectionKeys.walletToApp,
                    launch.sid,
                    IrohaConnectDirection.WALLET_TO_APP,
                    3,
                    response.aead,
                )
                val result = responseEnvelope.payload as IrohaConnectEnvelopePayload.SignResultOk
                assertTrue(
                    IrohaConnectCrypto.verifyEd25519(
                        account.publicKey,
                        message,
                        result.signature.signature,
                    ),
                )

                assertThrows(IrohaConnectSessionException::class.java) {
                    session.receive(requestFrame, 1_500)
                }

                val deniedEnvelope = IrohaConnectEnvelopeWire.encode(
                    4,
                    IrohaConnectEnvelopePayload.SignRaw(
                        "uranai.irohaconnect.unapproved-domain.v1",
                        "must not be signed".toByteArray(),
                    ),
                )
                val deniedCiphertext = IrohaConnectCrypto.encrypt(
                    appDirectionKeys.appToWallet,
                    4,
                    IrohaConnectWire.associatedData(
                        launch.sid,
                        IrohaConnectDirection.APP_TO_WALLET,
                        4,
                    ),
                    deniedEnvelope,
                )
                val deniedFrame = IrohaConnectWire.encodeCiphertext(
                    launch.sid,
                    4,
                    deniedCiphertext,
                    IrohaConnectDirection.APP_TO_WALLET,
                )
                val deniedResponse = session.receive(deniedFrame, 1_550)
                    as IrohaConnectSessionEvent.SendFrame
                assertFalse(deniedResponse.signed)
                val deniedResponseFrame = IrohaConnectWire.decodeFrame(deniedResponse.bytes)
                    as IrohaConnectFrame.Ciphertext
                val deniedError = IrohaConnectEnvelopeWire.decrypt(
                    appDirectionKeys.walletToApp,
                    launch.sid,
                    IrohaConnectDirection.WALLET_TO_APP,
                    4,
                    deniedResponseFrame.aead,
                ).payload as IrohaConnectEnvelopePayload.SignResultError
                assertEquals("PERMISSION_DENIED", deniedError.code)

                val closeFrame = IrohaConnectWire.decodeFrame(
                    requireNotNull(session.closeWithFrame("Interop test complete")),
                ) as IrohaConnectFrame.Ciphertext
                assertEquals(5, closeFrame.sequence)
                val closeEnvelope = IrohaConnectEnvelopeWire.decrypt(
                    appDirectionKeys.walletToApp,
                    launch.sid,
                    IrohaConnectDirection.WALLET_TO_APP,
                    5,
                    closeFrame.aead,
                )
                assertEquals(
                    "Interop test complete",
                    (closeEnvelope.payload as IrohaConnectEnvelopePayload.Close).reason,
                )
            } finally {
                appDirectionKeys.destroy()
            }
        } finally {
            session.close()
            account.destroy()
            fixture.appKeys.destroy()
        }
        assertTrue(session.isClosed)
    }

    @Test
    fun `unsupported transaction and unreadable raw payload never invoke signer`() {
        listOf(false, true).forEach { transaction ->
            val fixture = launchFixture("iroha", "https://taira.sora.org")
            val launch = IrohaConnectUri.parse(fixture.uri)
            val session = IrohaConnectWalletSession(launch, startedAtMillis = 1_000)
            val account = IrohaKeyDerivation.derive(MNEMONIC, NexusNetworks.taira)
            try {
                val permissions = IrohaConnectPermissions(
                    methods = listOf(if (transaction) "sign_transaction" else "sign_raw"),
                    events = emptyList(),
                    resources = if (transaction) null else listOf(URANAI_SIGNING_DOMAIN),
                )
                val open = IrohaConnectWire.encodeOpen(launch.sid, launch.appPublicKey,
                    launch.networkIdBytes, IrohaConnectAppMetadata("Example", "https://example.com", null), permissions)
                session.receive(open, 1_100)
                val approval = IrohaConnectWire.decodeFrame(session.approvePairing(account.address, 1_200) {
                    IrohaConnectCrypto.signEd25519(account.privateKeySeed, it)
                }.bytes) as IrohaConnectFrame.Control
                val walletKey = (approval.control as IrohaConnectControl.Approve).walletPublicKey
                val keys = IrohaConnectCrypto.deriveDirectionKeys(launch.sid, walletKey, fixture.appKeys.privateKey)
                try {
                    val payload = if (transaction) IrohaConnectEnvelopePayload.SignTransaction("opaque transaction".toByteArray())
                        else IrohaConnectEnvelopePayload.SignRaw(URANAI_SIGNING_DOMAIN, byteArrayOf(1, 2, 3))
                    val ciphertext = IrohaConnectCrypto.encrypt(keys.appToWallet, 2,
                        IrohaConnectWire.associatedData(launch.sid, IrohaConnectDirection.APP_TO_WALLET, 2),
                        IrohaConnectEnvelopeWire.encode(2, payload))
                    val request = session.receive(IrohaConnectWire.encodeCiphertext(launch.sid, 2,
                        ciphertext, IrohaConnectDirection.APP_TO_WALLET), 1_300) as IrohaConnectSessionEvent.SigningRequested
                    assertEquals(null, request.review.readableMessage)
                    var signerCalled = false
                    val result = session.approveRequest(request.review.requestToken, 1_400) {
                        signerCalled = true
                        IrohaConnectCrypto.signEd25519(account.privateKeySeed, it)
                    }
                    assertFalse(signerCalled)
                    assertFalse(result.signed)
                    val frame = IrohaConnectWire.decodeFrame(result.bytes) as IrohaConnectFrame.Ciphertext
                    val error = IrohaConnectEnvelopeWire.decrypt(keys.walletToApp, launch.sid,
                        IrohaConnectDirection.WALLET_TO_APP, 2, frame.aead).payload as IrohaConnectEnvelopePayload.SignResultError
                    assertEquals("UNSUPPORTED_SIGNING_CONTENT", error.code)
                } finally { keys.destroy() }
            } finally { session.close(); account.destroy(); fixture.appKeys.destroy() }
        }
    }

